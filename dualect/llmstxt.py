"""Generating ``llms.txt``: every rule in one line (docs/design.md section 6).

``llms.txt`` is the index an LLM reads first: it names each rule, says what it
covers and how far it is automated in each direction, and points at the
folder with the full knowledge (``rule.yaml``) and the verified cases. It is
generated from the rule folders (``dualect llms-txt -o llms.txt``) and a test
fails when the committed file is stale.
"""

from dualect.rulebook import Rule

HEADER = """\
# dualect

> Translates numeric code between .m files (Octave/MATLAB style) and Python/NumPy
> in both directions, one tested rule per construct, and verifies every
> translation by running both sides.

Each rule lives in `rules/<category>/<rule-id>/`: `rule.yaml` explains the
difference between the languages (`why`, `pitfalls`) for a human or an LLM,
`translate.py` holds the deterministic translators, and `cases/` holds `.m` /
`.py` pairs that run in both languages. A rule's status is given per direction:
`mechanical` (translated by its `translate.py`, every case verified), `guided`
(an LLM applies the rule; the result is verified) or `unsupported`. Use
`dualect scan FILE` for the rules a file needs and `dualect context FILE` for
them as prompt context; the MCP server (`dualect mcp`) offers the same as tools.
Generated by `dualect llms-txt`; do not edit by hand.

## Rules

"""


def rule_line(rule: Rule) -> str:
    """One rule as a single Markdown list item."""
    reverse = rule.python_status.value if rule.python_status is not None else "n/a"
    title = " ".join(rule.title.split())
    return (
        f"- [{rule.id}](rules/{rule.id}/rule.yaml): {title} "
        f"(.m to Python: {rule.status.value}; Python to .m: {reverse}; "
        f"{len(rule.cases)} case{'s' if len(rule.cases) != 1 else ''})"
    )


def render_llms_txt(*, rules: list[Rule]) -> str:
    """The whole file for the given rules (sorted by id).

    :param rules: all loaded rules.
    """
    lines = [rule_line(rule) for rule in sorted(rules, key=lambda r: r.id)]
    return HEADER + "\n".join(lines) + "\n"
